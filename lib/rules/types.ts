import type { TzModel } from "@/lib/tz/model";
import type { Derived } from "@/lib/tz/derive";

/**
 * Типы движка проверок (стадия 05 конвейера, этап 7–8 плана).
 *
 * Движок детерминированный: никакой языковой модели здесь нет и не будет.
 * Решение «выпускать документ или нет» принимают эти правила, а не Claude.
 */

export type Severity =
  /** Не даёт перевести документ в статус «Утверждён». */
  | "blocking"
  /** Требует от составителя явного обоснования, которое сохраняется в документе. */
  | "warning";

export type Finding = {
  ruleId: string;
  severity: Severity;
  /** Краткая формулировка нарушения — то, что видно в списке. */
  title: string;
  /** Что именно не так и что с этим делать. */
  detail: string;
  /** Шаг анкеты, куда ведёт переход по замечанию. */
  stepId?: string;
  /** Идентификатор акта в справочнике НПА — основание замечания. */
  actId?: string;
  /**
   * Стабильный ключ замечания: правило плюс якорь (код требования, индекс цели).
   * По нему хранится обоснование, поэтому ключ не должен меняться от правки
   * соседнего поля — иначе обоснование потеряется.
   */
  key: string;
};

export type RuleContext = {
  model: TzModel;
  derived: Derived;
};

export type Rule = {
  id: string;
  severity: Severity;
  /** Название правила для реестра — не текст замечания. */
  title: string;
  actId?: string;
  /**
   * Правила, для которых в модели ещё нет данных, остаются в реестре
   * с implemented: false. Реестр должен показывать полную картину проверок,
   * включая те, что ещё не работают, — иначе непонятно, чего документ не проверил.
   */
  implemented: boolean;
  check?: (ctx: RuleContext) => Finding[];
};

export type AuditResult = {
  findings: Finding[];
  blocking: Finding[];
  /** Предупреждения без обоснования — те, что ещё требуют действия. */
  unjustified: Finding[];
  /** Правила из реестра, которые пока не выполняются. */
  pending: Rule[];
  canApprove: boolean;
};
